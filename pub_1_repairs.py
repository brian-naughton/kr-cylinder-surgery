"""PUB-1 — the three proof repairs mandated at A33, machine-checked.

This runner exists only to certify the three named inputs the referee
round asked for.  It introduces NO new mathematics beyond them: each
check is a hygiene input to a proof already in the paper.

  R1  Factoriality of A[w], via Nagata's criterion, used to justify the
      gcd/content argument of §3.1.  Two sub-claims:
        (R1a)  A_x is a localised polynomial ring, hence a UFD:
               A_x = C[x^{+-1}, z, t] with y determined;
        (R1b)  x is prime in A[w], i.e. A[w]/(x) is a domain --
               A[w]/(x) = C[y,z,t,w]/(z^2 + t^3) and z^2 + t^3 is
               irreducible.
      Nagata: R a Noetherian domain, f prime, R_f a UFD  ==>  R a UFD.

  R2  The complete-intersection sentence of §4.3.  ONE bounded attempt
      (A33 R2) at the local certificate mu(I_m) = dim_k I_m / m I_m > 2
      at a suitable maximal ideal m of the centre.  mu is computed as
      the k-dimension of I/(m I + <the four generators' relations>) by
      linear algebra over the residue field, NOT by a Groebner call on
      a localisation.  If this does not land, the sentence is DELETED
      from the paper and this block records NOT-ATTEMPTED.

  R4  Smoothness of pi : Y_1 -> A^2_{t,q}, replacing the flatness
      appeal in §8.  The relative differential in the fibre coordinates
      (p, Z, H) is (-1-2p, -q, t^3); it vanishes only at p = -1/2,
      q = 0, t = 0, where W = 1/4 != 0, so no such point lies on
      Y_1 = V(W).  Smooth + surjective is the hypothesis the Gysin and
      localisation machinery of §8 actually wants.

Ledger: runs_synthesis/PUB-1-REPAIRS.json.  Mode I.
"""

