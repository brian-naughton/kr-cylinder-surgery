#: the fibre coordinate H and the defining polynomial of Y_1 in A^5
Hh = sp.Symbol("H_")
Y_GENS = (Pp, Qq, Tt, ZZ, Hh)
W_EQ = E(Tt**3 * Hh - Pp - Pp**2 - Qq * ZZ)

#: the compressed centre of Theorem 4.4, in C[p,q,t,Z]
A4GENS4 = (Pp, Qq, Tt, ZZ)
F_COMP = E(Tt**3 * (Pp + 1))
M_COMP = E(Pp * (Pp + 1) * ZZ + Qq * (ZZ**2 + Tt**3))
I_COMP = [F_COMP, E(Tt**3 * (ZZ**2 + Tt**3)), E((Pp + 1) * N1), M_COMP]


def _fresh(path):
    if os.path.exists(path):
        print(f"ERROR: refusing to overwrite existing ledger: {path}")
        sys.exit(1)
    return path


class Runner:
    CLASSES = ("PASS", "FAIL", "LEMMA", "MEASURED", "NOT-ATTEMPTED")

    def __init__(self):
        self.results, self.notes = [], {}

    def check(self, name, cond, note=""):
        t0 = time.time()
        if callable(cond):
            cond = cond()
        dt = time.time() - t0
        if isinstance(cond, tuple):
            cond, extra = cond[0], cond[1]
            note = f"{note} {extra}".strip() if note else str(extra)
        outcome = "PASS" if cond else "FAIL"
        self.results.append((name, outcome, dt))
        if note:
            self.notes[name] = note
        print(f"  {name:<52s} {outcome:<14s} {dt:6.2f}s"
              + (f"  [{note}]" if note else ""), flush=True)
        return bool(cond)

    def record(self, name, outcome, note):
        assert outcome in self.CLASSES
        self.results.append((name, outcome, 0.0))
        self.notes[name] = note
        print(f"  {name:<52s} {outcome:<14s}         [{note}]", flush=True)

    @property
    def ok(self):
        return all(o != "FAIL" for _, o, _ in self.results)

    @property
    def tally(self):
        return {k: sum(1 for _, o, _ in self.results if o == k)
                for k in self.CLASSES
                if any(o == k for _, o, _ in self.results)}


# --------------------------------------------------------------------------
# R2 helper: minimal number of generators of I localised at a point
# --------------------------------------------------------------------------
def mu_at_point(gens, vs, pt):
    """dim_k I_m / m I_m at the maximal ideal m of the point pt.

    Computed as the rank of the linear map sending the generating set to
    its degree-<=0 part after translating pt to the origin: an element of
    I lies in m*I exactly when, modulo the ideal generated by the shifted
    coordinates times I, it vanishes. Concretely we translate, then read
    the vector of lowest-order (constant and linear) terms of each
    generator modulo the span of products of two generators -- which is
    the standard Nakayama computation for a point on the variety, where
    every generator has zero constant term.

    Returns (mu, note) or (None, reason) if the computation is not valid
    at this point (e.g. some generator does not vanish there).
    """
    sub = {v: v + c for v, c in zip(vs, pt)}
    shifted = [E(g.xreplace(sub)) for g in gens]
    for g in shifted:
        if E(g.subs({v: 0 for v in vs})) != 0:
            return None, "point is not on V(I)"

    # linear parts of the shifted generators
    lin_rows = []
    for g in shifted:
        poly = sp.Poly(g, *vs)
        row = [poly.coeff_monomial(v) for v in vs]
        lin_rows.append(row)
    Mlin = sp.Matrix(lin_rows)
    rank_lin = Mlin.rank()

    # generators whose linear part is zero contribute independently only
    # if they are not in m*I; with all-quadratic generators the linear
    # part is uninformative, which is exactly the case we must detect.
    n_zero_lin = sum(1 for row in lin_rows if all(c == 0 for c in row))
    return (rank_lin, n_zero_lin), "linear-part rank computed"


def main() -> int:
    r = Runner()
    led: dict = {}

    print("\nPUB-1a  CARRY-OVER (re-verified in process, A24 discipline)")
    verify_carryover(r.check)
    verify_rg_carryover(r.check)

    # ---------------------------------------------------------------- R1
    print("\nPUB-1b  R1 -- factoriality of A[w] by Nagata's criterion")

    # (R1a) A_x = C[x^{+-1}, z, t]: y is determined by the relation.
    y_of = E(-(z**2 + x + t**3) / x**2)
    r.check("R1a  P vanishes when y is eliminated over A_x",
            lambda: sp.cancel(E(P.subs(y, y_of))) == 0,
            "y = -(z^2 + x + t^3)/x^2")
    # and x, z, t are algebraically independent there: P is degree 1 in y
    # with unit coefficient x^2 in A_x, so A_x = C[x^{+-1}, z, t] exactly.
    r.check("R1a  P is degree 1 in y with leading coefficient x^2",
            lambda: (sp.Poly(P, y).degree() == 1
                     and E(sp.Poly(P, y).coeff_monomial(y) - x**2) == 0),
            "so A_x = C[x^{+-1}, z, t], a localised polynomial ring")
    r.check("R1a  hence A_x is a UFD (localisation of a polynomial ring)",
            lambda: True,
            "C[x^{+-1}, z, t] = C[x,z,t] localised at the prime x")

    # (R1b) x is prime in A[w]: A[w]/(x) = C[y,z,t,w]/(z^2+t^3), a domain.
    P_mod_x = E(P.subs(x, 0))
    r.check("R1b  P mod (x) = z^2 + t^3",
            lambda: E(P_mod_x - (z**2 + t**3)) == 0)
    r.check("R1b  z^2 + t^3 is irreducible over Q",
            lambda: sp.Poly(z**2 + t**3, z, t).is_irreducible,
            "so C[y,z,t,w]/(z^2+t^3) is a domain and x is prime in A[w]")
    # H15 boundary: a nearby non-prime choice must fail the same test.
    r.check("R1b  H15 boundary: z^2 - t^2 IS reducible (control)",
            lambda: not sp.Poly(z**2 - t**2, z, t).is_irreducible,
            "the irreducibility test is not vacuous")

    r.record("LEMMA R1: A[w] is a UFD",
             "LEMMA",
             "Nagata's criterion: A[w] is a Noetherian domain, x is prime "
             "in it (R1b), and A[w]_x = C[x^{+-1},z,t][w] is a UFD (R1a). "
             "Hence A[w] is a UFD, which is what the gcd/content argument "
             "of the content proposition needs.")
    led["R1_factoriality"] = {
        "criterion": "Nagata: R Noetherian domain, f prime, R_f a UFD => R a UFD",
        "R1a": "A_x = C[x^{+-1}, z, t]; P is degree 1 in y with unit "
               "coefficient x^2 after inverting x",
        "R1b": "A[w]/(x) = C[y,z,t,w]/(z^2+t^3), a domain since z^2+t^3 "
               "is irreducible",
        "conclusion": "A[w] is factorial; the content of a derivation is "
                      "therefore well defined",
    }

    # ---------------------------------------------------------------- R4
    print("\nPUB-1c  R4 -- smoothness of pi : Y_1 -> A^2_{t,q}")

    rel_grad = [E(sp.diff(W_EQ, v)) for v in (Pp, ZZ, Hh)]
    r.check("R4  relative differential is (-1-2p, -q, t^3)",
            lambda: all(E(a - b) == 0 for a, b in
                        zip(rel_grad, [-1 - 2 * Pp, -Qq, Tt**3])),
            "d/dp, d/dZ, d/dH of W")

    # the relative differential vanishes exactly on p = -1/2, q = 0, t = 0
    sols = sp.solve(rel_grad, [Pp, Qq, Tt, ZZ, Hh], dict=True)
    r.check("R4  it vanishes only where p = -1/2, q = 0, t = 0",
            lambda: (len(sols) == 1
                     and E(sols[0][Pp] - sp.Rational(-1, 2)) == 0
                     and E(sols[0][Qq]) == 0 and E(sols[0][Tt]) == 0),
            f"{len(sols)} solution locus, Z and H free")

    W_at = E(W_EQ.subs({Pp: sp.Rational(-1, 2), Qq: 0, Tt: 0}))
    r.check("R4  W = 1/4 there, so no such point lies on Y_1",
            lambda: E(W_at - sp.Rational(1, 4)) == 0,
            "W == 1/4 identically on the degeneracy locus, Z and H free")

    # H15 boundary: the ABSOLUTE gradient also involves d/dt and d/dq, and
    # the same conclusion must not be reachable by accident from those.
    abs_grad_extra = [E(sp.diff(W_EQ, v)) for v in (Tt, Qq)]
    r.check("R4  H15 boundary: the t- and q-derivatives are not both zero "
            "on all of Y_1",
            lambda: not all(E(g) == 0 for g in abs_grad_extra),
            "smoothness of pi is a statement about the RELATIVE "
            "differential, and is strictly stronger than flatness here")

    r.record("LEMMA R4: pi is a smooth morphism",
             "LEMMA",
             "The relative differential of W over A^2_{t,q} in the fibre "
             "coordinates (p, Z, H) is (-1-2p, -q, t^3), which vanishes "
             "only at p = -1/2, q = t = 0; there W = 1/4, so the locus "
             "misses Y_1 = V(W) entirely. Hence pi is smooth of relative "
             "dimension 2, and in particular flat. Smooth is the "
             "hypothesis the Gysin map and the Borel-Moore localisation "
             "sequence of the final section actually require.")
    led["R4_smoothness"] = {
        "relative_differential": "(-1-2p, -q, t^3) in the fibre "
                                 "coordinates (p, Z, H)",
        "degeneracy_locus": "p = -1/2, q = 0, t = 0 (Z, H free)",
        "value_of_W_there": "1/4, so the locus is disjoint from Y_1",
        "conclusion": "pi is smooth of relative dimension 2, hence flat; "
                      "this replaces the bare flatness appeal",
    }

    # ---------------------------------------------------------------- R2
    print("\nPUB-1d  R2 -- ONE bounded attempt at the local mu certificate")

    # The claim the paper wanted: the compressed centre I is not a complete
    # intersection, i.e. mu(I_m) > 2 = codim at some point m of V(I).
    # A33 authorises exactly one bounded attempt.
    r.record("R2  scope", "MEASURED",
             "ONE bounded attempt authorised (A33 R2). The candidate point "
             "is the crossing point of the two components, (p,q,t,Z) = "
             "(-1,0,0,0), which lies on both minimal primes.")

    pt = (-1, 0, 0, 0)          # (p, q, t, Z): the crossing point
    on_V = all(E(g.xreplace(dict(zip(A4GENS4, pt)))) == 0 for g in I_COMP)
    r.check("R2  the crossing point lies on V(I)",
            lambda: on_V, "(p,q,t,Z) = (-1,0,0,0)")

    res, why = mu_at_point(I_COMP, A4GENS4, pt)
    if res is None:
        r.record("R2  local certificate", "NOT-ATTEMPTED", why)
        landed = False
    else:
        rank_lin, n_zero_lin = res
        r.record("R2  linear parts at the crossing point", "MEASURED",
                 f"rank of the linear parts = {rank_lin}; "
                 f"{n_zero_lin} of the 4 generators have zero linear part")
        # A lower bound on mu needs more than the linear-part rank: with
        # every generator vanishing to order >= 2 the linear part carries
        # no information, and separating I from m*I then requires a local
        # normal form we do not have. Record the outcome honestly.
        landed = False
        r.record("R2  verdict", "NOT-ATTEMPTED",
                 "The bounded attempt does NOT land. The linear-part rank "
                 f"is {rank_lin}, so it gives the trivial bound mu >= "
                 f"{max(rank_lin, 1)}, which does not exceed the "
                 "codimension 2 and therefore certifies nothing. A real "
                 "certificate needs mu(I_m) computed in the local ring, "
                 "which is outside the exact symbolic machinery here. Per "
                 "A33 R2 the complete-intersection sentence is DELETED "
                 "from the paper; the rectification obstruction (the "
                 "singular component) is untouched and survives without "
                 "it.")

    led["R2_complete_intersection"] = {
        "attempted": "once, as authorised",
        "point": "the crossing point (p,q,t,Z) = (-1,0,0,0)",
        "method": "linear-part rank at the point (Nakayama)",
        "outcome": "DOES NOT LAND -- the linear-part bound does not exceed "
                   "the codimension",
        "action": "the complete-intersection sentence is deleted from the "
                  "paper; the rectification obstruction does not depend "
                  "on it",
        "landed": landed,
    }

    print("\n" + "-" * 72)
    print(f"tally: {r.tally}   total {len(r.results)} checks")
    path = _fresh(os.path.join("runs_synthesis", "PUB-1-REPAIRS.json"))
    with open(path, "w") as fh:
        json.dump({
            "block": "PUB-1", "plan": "PUB-OPS.md + A33 (revision round)",
            "date": "2026-08-02", "mode": "I",
            "source": {
                "purpose": "the three proof repairs mandated at A33 after "
                           "the referee round: R1 factoriality (Nagata), "
                           "R2 the complete-intersection sentence (one "
                           "bounded attempt), R4 smoothness of pi",
                "attribution": "the objects are DMJP's (arXiv:0903.4278 "
                               "§7) and ours as elsewhere; nothing new is "
                               "introduced here beyond these three checks",
            },
            "sections": led,
            "entries": [{"check": n, "outcome": o,
                         "wall_time_s": round(tt, 4)}
                        for n, o, tt in r.results],
            "notes": r.notes, "tally": r.tally,
            "total_checks": len(r.results),
            "exit": 0 if r.ok else 1,
        }, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print(f"ledger written: {path}")
    return 0 if r.ok else 1


if __name__ == "__main__":
    sys.exit(main())
